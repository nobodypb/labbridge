#!/usr/bin/env python3
"""Assemble public API and firmware module descriptors from one source tree."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def validation_schema(schema):
    """Drop prose at schema nodes, preserving property names and constraints."""
    if not isinstance(schema, dict):
        return schema
    result = {}
    for key, value in schema.items():
        if key in {"description", "title", "example", "examples", "externalDocs"}:
            continue
        if key == "properties":
            value = {name: validation_schema(child) for name, child in value.items()}
        elif key in {"items", "additionalProperties", "not"}:
            value = validation_schema(value)
        elif key in {"allOf", "anyOf", "oneOf"}:
            value = [validation_schema(child) for child in value]
        result[key] = value
    return result


def assemble():
    spec = json.loads((ROOT / "api/core.json").read_text())
    modules = []
    for path in sorted((ROOT / "api/modules").glob("*.json")):
        fragment = json.loads(path.read_text())
        for name, value in fragment["paths"].items():
            if name in spec["paths"]:
                raise ValueError(f"Duplicate path {name}")
            spec["paths"][name] = value
        for name, value in fragment["schemas"].items():
            if name in spec["components"]["schemas"]:
                raise ValueError(f"Duplicate schema {name}")
            spec["components"]["schemas"][name] = value
        modules.append(fragment["x-labbridge-module"])
    spec["x-labbridge-modules"] = modules
    operations = []
    for path, item in spec["paths"].items():
        for method, value in item.items():
            if method not in ("get", "put", "post", "delete"):
                continue
            operations.append((value["operationId"], method.upper(), path))
    header = "// Generated by tools/assemble_api.py. Do not edit.\n#pragma once\n#include <cstddef>\nnamespace labbridge::generated {\nstruct Route { const char *operation; const char *method; const char *path; };\ninline constexpr Route routes[] = {\n"
    header += "".join(
        "  {" + ", ".join(json.dumps(x) for x in route) + "},\n" for route in operations
    )
    header += "};\ninline constexpr std::size_t route_count=sizeof(routes)/sizeof(routes[0]);\n}\n"
    requests = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "put", "post", "delete"):
                continue
            if "requestBody" in op:
                requests[op["operationId"]] = op["requestBody"]["content"][
                    "application/json"
                ]["schema"]

    # Request validation does not need to allocate the response schemas on an ESP.
    def refs(value):
        if isinstance(value, dict):
            if "$ref" in value:
                yield value["$ref"].rsplit("/", 1)[-1]
            for child in value.values():
                yield from refs(child)
        elif isinstance(value, list):
            for child in value:
                yield from refs(child)

    needed = set(refs(requests))
    pending = list(needed)
    while pending:
        name = pending.pop()
        for child in refs(spec["components"]["schemas"][name]):
            if child not in needed:
                needed.add(child)
                pending.append(child)
    schemas = {name: spec["components"]["schemas"][name] for name in sorted(needed)}
    constraints = json.dumps(
        {
            "schemas": {
                name: validation_schema(value) for name, value in schemas.items()
            },
            "requests": {
                name: validation_schema(value) for name, value in requests.items()
            },
        },
        separators=(",", ":"),
    )
    header += (
        'namespace labbridge::generated { inline constexpr const char* constraints=R"SCHEMA('
        + constraints
        + ')SCHEMA"; }\n'
    )
    # Keep only the selected request's reachable rules in RAM while validating.
    # The complete contract above remains available for annotation/drift checks.
    header += "namespace labbridge::generated {\nstruct RequestRule { const char *operation; const char *constraints; };\ninline constexpr RequestRule request_rules[] = {\n"
    for operation, request in requests.items():
        reachable = set(refs(request))
        pending = list(reachable)
        while pending:
            name = pending.pop()
            for child in refs(spec["components"]["schemas"][name]):
                if child not in reachable:
                    reachable.add(child)
                    pending.append(child)
        document = json.dumps(
            {
                "request": validation_schema(request),
                "schemas": {
                    name: validation_schema(spec["components"]["schemas"][name])
                    for name in sorted(reachable)
                },
            },
            separators=(",", ":"),
        )
        header += (
            "  {" + json.dumps(operation) + ', R"SCHEMA(' + document + ')SCHEMA"},\n'
        )
    header += "};\n}\n"
    return {
        ROOT / "api/openapi.json": json.dumps(spec, indent=2) + "\n",
        ROOT / "firmware/generated/routes.hpp": header,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in assemble().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"Generated artifact differs: {path.relative_to(ROOT)}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
