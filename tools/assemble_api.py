#!/usr/bin/env python3
"""Assemble public API and firmware module descriptors from one source tree."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def assemble():
    spec = json.loads((ROOT / "api/core.json").read_text())
    modules = []
    for path in sorted((ROOT / "api/modules").glob("*.json")):
        fragment = json.loads(path.read_text())
        for name, value in fragment["paths"].items():
            if name in spec["paths"]:
                raise ValueError(f"Duplicate path {name}")
            spec["paths"][name] = value
        for name, value in fragment["schemas"].items():
            if name in spec["components"]["schemas"]:
                raise ValueError(f"Duplicate schema {name}")
            spec["components"]["schemas"][name] = value
        modules.append(fragment["x-labbridge-module"])
    spec["x-labbridge-modules"] = modules
    operations = []
    for path, item in spec["paths"].items():
        for method, value in item.items():
            if method not in ("get", "put", "post", "delete"):
                continue
            operations.append((value["operationId"], method.upper(), path))
    header = "// Generated by tools/assemble_api.py. Do not edit.\n#pragma once\n#include <cstddef>\nnamespace labbridge::generated {\nstruct Route { const char *operation; const char *method; const char *path; };\ninline constexpr Route routes[] = {\n"
    header += "".join(
        "  {" + ", ".join(json.dumps(x) for x in route) + "},\n" for route in operations
    )
    header += "};\ninline constexpr std::size_t route_count=sizeof(routes)/sizeof(routes[0]);\n}\n"
    requests = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "put", "post", "delete"):
                continue
            if "requestBody" in op:
                requests[op["operationId"]] = op["requestBody"]["content"][
                    "application/json"
                ]["schema"]

    # Request validation does not need to allocate the response schemas on an ESP.
    def refs(value):
        if isinstance(value, dict):
            if "$ref" in value:
                yield value["$ref"].rsplit("/", 1)[-1]
            for child in value.values():
                yield from refs(child)
        elif isinstance(value, list):
            for child in value:
                yield from refs(child)

    needed = set(refs(requests))
    pending = list(needed)
    while pending:
        name = pending.pop()
        for child in refs(spec["components"]["schemas"][name]):
            if child not in needed:
                needed.add(child)
                pending.append(child)
    schemas = {name: spec["components"]["schemas"][name] for name in sorted(needed)}
    constraints = json.dumps(
        {"schemas": schemas, "requests": requests}, separators=(",", ":")
    )
    header += (
        'namespace labbridge::generated { inline constexpr const char* constraints=R"SCHEMA('
        + constraints
        + ')SCHEMA"; }\n'
    )
    return {
        ROOT / "api/openapi.json": json.dumps(spec, indent=2) + "\n",
        ROOT / "firmware/generated/routes.hpp": header,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in assemble().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"Generated artifact differs: {path.relative_to(ROOT)}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
